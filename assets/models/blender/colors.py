# Writes src/shared/MeshColors.lua: the colour of every part in tidebound_models.obj,
# read from its material in the .mtl (Blender writes linear colours; Roblox wants sRGB).
# Run: python3 assets/models/blender/colors.py   (from the repo root)
import re
base = 'assets/models/tidebound_models'
kd, cur = {}, None
for l in open(base + '.mtl'):
    if l.startswith('newmtl '): cur = l.split(None, 1)[1].strip()
    elif l.startswith('Kd ') and cur: kd[cur] = [float(x) for x in l.split()[1:4]]
def srgb(c):
    c = 12.92 * c if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055
    return max(0, min(255, round(c * 255)))
parts, group = {}, None
for l in open(base + '.obj'):
    if l.startswith('g '): group = l[2:].strip()
    elif l.startswith('usemtl ') and group and group not in parts:
        parts[group] = l.split(None, 1)[1].strip()
out = ['-- Generated by assets/models/blender/colors.py. Do not edit by hand.',
       '-- part name -> { colour, material name }', 'return {']
for g in sorted(parts):
    m = parts[g]; r, gg, b = (srgb(x) for x in kd[m])
    out.append(f'\t["{g}"] = {{ Color3.fromRGB({r}, {gg}, {b}), "{re.sub(r"[.]\d+$", "", m)}" }},')
out.append('}')
open('src/shared/MeshColors.lua', 'w').write('\n'.join(out) + '\n')
print(len(parts), 'parts')
